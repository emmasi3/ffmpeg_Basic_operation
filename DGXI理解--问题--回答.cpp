/**************************************************************
 * 【问题背景】
 *
 * 我在使用 DXGI Desktop Duplication（IDXGIOutputDuplication）
 * 进行屏幕采集时，产生了一个核心疑问：
 *
 *   —— 我如何“限制 DXGI 采集屏幕的频率”？
 *
 * 因为直觉上：
 *   1）设备一旦打开，似乎就一直在“抓屏”
 *   2）没有显式的 FPS / interval 参数
 *   3）难道 GPU 会无缘无故地一直采集桌面？
 *
 **************************************************************/


 /**************************************************************
  * 【最初的直觉理解（存在误区）】
  *
  * ❌ 误区描述：
  *
  *   “DXGI 设备在抓取屏幕”
  *   “每次调用 AcquireNextFrame()，设备就去抓一帧屏幕”
  *
  * 这种理解隐含了一个前提：
  *   → GPU / DXGI 是‘主动’截图桌面的
  *
  * 但这是不准确的。
  *
  **************************************************************/


  /**************************************************************
   * 【关键澄清 1：GPU 从来不会‘抓屏幕’】
   *
   * ✔ 正确事实：
   *
   *   GPU 的职责只有一件事：
   *     —— 渲染应用画面 + Present 到屏幕
   *
   *   GPU 不存在：
   *     - “截图桌面”
   *     - “为录屏工具单独生成帧”
   *
   *   桌面图像 = GPU 已经渲染完成并 Present 的结果
   *
   **************************************************************/


   /**************************************************************
	* 【关键澄清 2：DXGI Desktop Duplication 是“被动副本”】
	*
	* DXGI Desktop Duplication 的真实行为是：
	*
	*   1）GPU / DWM 发生 Present（桌面发生可见更新）
	*   2）DXGI 在内部维护一个“桌面帧副本”
	*   3）这个副本随 GPU Present 自动更新
	*
	* ⚠ 注意：
	*   - DXGI 不会要求 GPU 额外渲染
	*   - DXGI 不会主动制造新帧
	*
	**************************************************************/


	/**************************************************************
	 * 【AcquireNextFrame() 的真实含义】
	 *
	 * HRESULT AcquireNextFrame(...)
	 *
	 * ❌ 它不是：
	 *   “抓取一帧屏幕”
	 *   “触发 GPU 截图”
	 *
	 * ✔ 它真正做的是：
	 *   “获取 DXGI 已经准备好的‘最新桌面帧副本’”
	 *
	 * 类比：
	 *   GPU/DWM：往信箱里放信（帧）
	 *   AcquireNextFrame：你去信箱取信
	 *
	 **************************************************************/


	 /**************************************************************
	  * 【TimeoutInMilliseconds 的真正作用】
	  *
	  * AcquireNextFrame(timeout, ...)
	  *
	  * timeout 表示：
	  *   —— 如果当前没有新帧，我最多等多久
	  *
	  * 它 ❌ 不是：
	  *   - 帧率
	  *   - 帧间隔
	  *   - 捕获周期
	  *
	  * 它 ✔ 是：
	  *   - 阻塞等待上限
	  *
	  **************************************************************/


	  /**************************************************************
	   * 【“新的一帧桌面数据”什么时候产生？】
	   *
	   * 桌面新帧的产生条件：
	   *
	   *   ✔ 有程序调用 Present()
	   *   ✔ DWM 进行一次桌面合成
	   *   ✔ 窗口动画 / 光标变化 / UI 变化
	   *
	   * 常见情况下：
	   *   - DWM 以显示器刷新率（如 60Hz）工作
	   *
	   * 所以：
	   *   桌面帧 ≈ 显示器刷新节奏
	   *
	   **************************************************************/


	   /**************************************************************
		* 【核心结论（你的最终正确理解）】
		*
		* ✔ “设备抓取屏幕数据” 这个说法本身不准确
		*
		* ✔ 正确描述应该是：
		*
		*   GPU 从不抓取桌面图像
		*   GPU 只是不断渲染并 Present 画面
		*   DXGI 只是保存这些 Present 结果的副本
		*   AcquireNextFrame 只是获取这个副本
		*
		**************************************************************/


		/**************************************************************
		 * 【那‘限制 DXGI 采集频率’到底意味着什么？】
		 *
		 * ✔ 本质含义：
		 *   “限制我自己去取帧的频率”
		 *
		 * ❌ 不是：
		 *   - 控制 GPU 出帧
		 *   - 控制 DXGI 生成帧
		 *
		 **************************************************************/


		 /**************************************************************
		  * 【可控手段（应用层，唯一正确做法）】
		  *
		  * 方法 1：控制 AcquireNextFrame 调用频率
		  *
		  *   - 30 FPS → 每 ~33ms 调用一次
		  *   - 60 FPS → 每 ~16ms 调用一次
		  *
		  * 方法 2：基于 DXGI_OUTDUPL_FRAME_INFO 时间戳
		  *
		  *   - frameInfo.LastPresentTime
		  *   - 只处理满足时间间隔的帧
		  *
		  * 方法 3：允许丢帧（AccumulatedFrames）
		  *
		  *   - DXGI 内部会自动丢弃你没取的帧
		  *
		  **************************************************************/


		  /**************************************************************
		   * 【一句话总结（终极心智模型）】
		   *
		   *   DXGI 不采集桌面
		   *   GPU 不截图
		   *   DXGI 只是“帧副本提供者”
		   *   AcquireNextFrame 只是“取最新帧”
		   *   采集频率 = 你取帧的频率
		   *
		   **************************************************************/

