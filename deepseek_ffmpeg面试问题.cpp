// ----------------------------------------------------------------
// Q1: 智能指针有哪几种？什么场景用 shared_ptr，什么场景用 unique_ptr？
// ----------------------------------------------------------------
// unique_ptr：独占所有权，不可拷贝，只可移动。用于明确单一所有者的场景
//              （如工厂函数返回值、PIMPL 惯用法）。
// shared_ptr：共享所有权，引用计数，当最后一个 shared_ptr 销毁时释放资源。
//             用于多个对象共享同一资源的场景。
// weak_ptr：不增加引用计数，用于打破 shared_ptr 循环引用
//           （如观察者模式、缓存系统中）。
//
// 典型代码示例：
//
//   // unique_ptr：FFmpeg 封装中管理 AVFormatContext 的典型用法
//   std::unique_ptr<AVFormatContext, decltype(&avformat_close_input)>
//       fmt_ctx(nullptr, avformat_close_input);
//
//   // shared_ptr：多个解码器共享同一帧缓冲池
//   auto frame_pool = std::make_shared<FramePool>();


