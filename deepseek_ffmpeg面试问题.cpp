// ----------------------------------------------------------------
// Q10: RTMP 和 RTSP 的区别？各适合什么场景？
// ----------------------------------------------------------------
//
// | 维度       | RTMP                              | RTSP                              |
// |------------|-----------------------------------|-----------------------------------|
// | 全称       | Real-Time Messaging Protocol      | Real-Time Streaming Protocol      |
// | 传输层     | TCP（可靠）                        | TCP(信令) + RTP/UDP(媒体) 或 TCP  |
// | 默认端口   | 1935                              | 554                               |
// | 厂商       | Adobe                             | IETF 标准                         |
// | 延迟       | 1-3 秒（低延迟模式可 < 1s）        | 通常 < 500ms                      |
// | 适用场景   | 直播推流/拉流                      | 监控摄像头、点播 VOD               |
// | 穿透性     | 较好（基于 HTTP 的变体 RTMPT）      | 一般                              |
// | 播放器支持 | Flash（已淘汰）、H5 需 WebRTC 网关  | VLC、FFplay、原生播放器            |
//
// 实际选型：
//   - 直播推流 → RTMP（OBS 推流到服务器的标准协议）
//   - 监控/安防 IPC → RTSP
//   - 现代 Web 直播 → SRT / WebRTC / LL-HLS


// ----------------------------------------------------------------
// Q11: HLS 的工作原理是什么？.m3u8 文件包含什么？
// ----------------------------------------------------------------
// HLS（HTTP Live Streaming）是 Apple 的流媒体协议，核心思想是：
// 将直播流切成小 TS 片段，通过 HTTP 分发。
//
//   直播推流 → 服务器切片 → CDN 分发 → 客户端播放
//                │
//                ├── playlist.m3u8       (索引文件，指向各 TS 片段)
//                ├── segment-001.ts      (3-10 秒的视频片段)
//                ├── segment-002.ts
//                └── ...
//
// m3u8 文件结构：
//
//   #EXTM3U
//   #EXT-X-VERSION:3
//   #EXT-X-TARGETDURATION:10          # 每个 TS 最长 10 秒
//   #EXT-X-MEDIA-SEQUENCE:0           # 第一个 TS 的序号
//   #EXTINF:9.009,                    # segment-000.ts 时长
//   segment-000.ts
//   #EXTINF:9.009,
//   segment-001.ts
//   #EXTINF:3.003,
//   segment-002.ts
//
// 延迟分析：标准 HLS 延迟 10-30 秒（3 个片段的延迟），
// LL-HLS（Low-Latency HLS）通过部分片段和 HTTP/2 push 可降到 2-6 秒。


// ----------------------------------------------------------------
// Q12: WebRTC 的 ICE、STUN、TURN 分别解决什么问题？
// ----------------------------------------------------------------
// WebRTC 的核心挑战是 P2P 穿透——两个位于 NAT 后的设备如何直接通信。
//
// | 组件 | 作用                         | 原理                                          |
// |------|------------------------------|-----------------------------------------------|
// | STUN | 获取公网 IP 地址              | 客户端向 STUN 服务器发请求，返回公网 IP:Port   |
// | TURN | 中继转发（兜底方案）           | 当 P2P 无法建立时，通过 TURN 服务器中转媒体数据 |
// | ICE  | 收集并选择最优连接路径         | 收集本地/STUN/TURN 地址作为 candidate，择优连通 |
//
//   优先：P2P 直连 (host candidate)
//      ↓ 失败
//   其次：NAT 穿透 (srflx candidate, 通过 STUN)
//      ↓ 失败
//   兜底：中继转发 (relay candidate, 通过 TURN)
//
// 面试常问："WebRTC 延迟为什么能做到 < 500ms？"
// → 因为 P2P 直连路径最短，不经过服务器中转。


