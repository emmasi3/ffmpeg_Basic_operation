// ----------------------------------------------------------------
// Q4: 解释 PTS、DTS、GOP 分别是什么？
// ----------------------------------------------------------------
//
// | 概念 | 全称                      | 含义                        | 关系           |
// |------|---------------------------|-----------------------------|----------------|
// | PTS  | Presentation Time Stamp   | 显示时间戳——何时显示这一帧   | 用户看到的顺序  |
// | DTS  | Decode Time Stamp         | 解码时间戳——何时解码这一帧   | 解码器处理顺序  |
// | GOP  | Group of Pictures         | 一个 I 帧到下一个 I 帧之间   | 决定随机访问粒度|
//
// - I 帧：帧内编码，可独立解码（关键帧）
// - P 帧：前向预测，依赖前面的 I/P 帧
// - B 帧：双向预测，依赖前后帧
//
// 为什么 PTS 和 DTS 可能不同？因为 B 帧需要参考未来帧，必须等后续帧先解码：
//
//   编码顺序(DTS): I₀  P₃  B₁  B₂  P₆  B₄  B₅
//   显示顺序(PTS): I₀  B₁  B₂  P₃  B₄  B₅  P₆


// ----------------------------------------------------------------
// Q5: H.264 的 NALU 类型有哪些？SPS/PPS 的作用是什么？
// ----------------------------------------------------------------
// H.264 裸流由 NALU（Network Abstraction Layer Unit）组成，主要类型：
//
// | NALU 类型 | 名称                              | 作用                                |
// |-----------|-----------------------------------|-------------------------------------|
// | SPS       | Sequence Parameter Set            | 序列级参数：分辨率、帧率、Profile/Level |
// | PPS       | Picture Parameter Set             | 图像级参数：熵编码模式、片组信息        |
// | IDR       | Instantaneous Decoder Refresh     | 即时刷新帧（I 帧的一种），可立即开始解码 |
// | SEI       | Supplemental Enhancement Info     | 补充信息                            |
//
// 关键点：
//   - SPS + PPS 是解码的前提，丢失后必须等下一个 IDR 才能恢复
//   - 打包 H.264 为 FLV/RTMP 时，通常把 SPS/PPS 放在
//     AVCDecoderConfigurationRecord 中
//   - 封装与裸流的区别：MP4/FLV 中 SPS/PPS 存于 extradata；
//     裸流（Annex-B）以 0x00000001 起始码分隔


// ----------------------------------------------------------------
// Q6: 音频中的采样率、位深、声道数、码率之间如何计算？
// ----------------------------------------------------------------
//
//   码率(bps) = 采样率 × 位深 × 声道数
//
// 例：CD 质量音频
//   采样率 = 44100 Hz
//   位深 = 16 bit
//   声道数 = 2 (立体声)
//   未压缩码率 = 44100 × 16 × 2 = 1,411,200 bps ≈ 1.4 Mbps
//
// AAC 音频帧计算：
//   一帧 AAC = 1024 个采样点（不是字节！）
//   一帧时长 = 1024 / 采样率（秒）
//   一帧原始 PCM 大小 = 1024 × 位深/8 × 声道数（字节）


