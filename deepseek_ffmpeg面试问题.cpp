// ----------------------------------------------------------------
// Q7: 描述 FFmpeg 解封装→解码→编码→封装的完整流程，画出涉及的 API 调用链。
// ----------------------------------------------------------------
//
//   解封装                                    编码                           封装
//   ┌──────────────────┐    ┌─────────────────┐    ┌──────────────────┐
//   │ avformat_open_input│   │ avcodec_send_frame│   │ avformat_write_header│
//   │ avformat_find_stream_info│→│ avcodec_receive_packet│→│ av_interleaved_write_frame│
//   │ av_read_frame     │   │                 │    │ av_write_trailer  │
//   └──────────────────┘    └─────────────────┘    └──────────────────┘
//           ↓                        ↑                       ↑
//       AVPacket                AVPacket               AVPacket
//           ↓                        ↓
//   ┌──────────────────┐    ┌─────────────────┐
//   │ avcodec_send_packet│   │ avcodec_receive_frame│
//   │ avcodec_receive_frame│   │ sws_scale / swr_convert │
//   │ (解码)            │    │ (格式转换)       │
//   └──────────────────┘    └─────────────────┘
//
// 核心步骤：
// 1. avformat_open_input + avformat_find_stream_info 打开并探测流信息
// 2. 对每个流 avcodec_find_decoder + avcodec_open2 打开解码器
// 3. 循环 av_read_frame → avcodec_send_packet → avcodec_receive_frame 解码
// 4. 可选：sws_scale（视频格式/尺寸转换）、swr_convert（音频重采样）
// 5. 编码侧反之：avcodec_send_frame → avcodec_receive_packet
// 6. av_interleaved_write_frame 写入封装容器


// ----------------------------------------------------------------
// Q8: av_read_frame 返回的 AVPacket 和 avcodec_receive_frame 返回的
//     AVFrame 区别是什么？
// ----------------------------------------------------------------
//
// | 对比维度 | AVPacket              | AVFrame                        |
// |----------|-----------------------|--------------------------------|
// | 层面     | 压缩域（编码后/封装层） | 非压缩域（原始数据）             |
// | 内容     | 编码后的码流数据       | 原始像素(YUV/RGB)或原始音频(PCM) |
// | 大小     | 通常较小（压缩后）     | 通常很大（1080p YUV420p 约 3MB） |
// | 内存管理 | av_packet_alloc/free   | av_frame_alloc/free            |
// | 关键字段 | pts, dts, stream_index, duration | pts, width, height, format, data[], linesize[] |
// | 引用计数 | av_packet_ref/unref    | av_frame_ref/unref             |


// ----------------------------------------------------------------
// Q9: FFmpeg 中的时间基（time_base）是什么？如何将 PTS 转换为秒？
// ----------------------------------------------------------------
// time_base 是一个 AVRational 结构体 {num, den}，表示一个时间戳单位的秒数。
//
//   时间(秒) = PTS × time_base.num / time_base.den
//            = PTS × av_q2d(time_base)
//
// 常见误区：
//   - 不同流（视频流、音频流）的 time_base 不同
//   - 视频流常用 1/90000 或 1/(帧率)（如 1/30）
//   - 音频流常用 1/采样率（如 1/44100）
//
//   // 正确的时间戳转换
//   double pts_seconds = av_q2d(video_stream->time_base) * frame->pts;
//
//   // 时间戳再转换到另一个时间基
//   int64_t new_pts = av_rescale_q(frame->pts, src_time_base, dst_time_base);


