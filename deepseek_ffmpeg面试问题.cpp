// Q15: 让你设计一个低延迟直播播放器，你会如何选型和架构？
// ----------------------------------------------------------------
//
// ┌──────────────────────────────────────────────┐
// │                  播放器架构                     │
// ├────────┬────────┬────────┬────────┬──────────┤
// │  输入层  │  解封装  │  解码层  │  渲染层  │  控制层   │
// │         │         │         │         │          │
// │ RTMP/   │ FFmpeg  │ 硬解码  │ OpenGL  │ 音画同步  │
// │ SRT/    │ avformat│ (Video  │ D3D11   │ 缓冲管理  │
// │ WebRTC  │         │ Toolbox │ SDL     │ Seek/ABR │
// │         │         │ DXVA2)  │ Audio   │          │
// │         │         │         │ render  │          │
// └────────┴────────┴────────┴────────┴──────────┘
//
// 低延迟关键点：
//   1. 传输层选 SRT/WebRTC 而非 RTMP（SRT 有更好的丢包恢复）
//   2. 禁用 B 帧编码，减少解码等待
//   3. 调小 FFmpeg 缓冲区：av_dict_set(&opts, "buffer_size", "102400", 0)
//   4. 硬解码优先（VideoToolbox/DXVA2/NVDEC），减少 CPU 耗时
//   5. 音视频同步阈值收紧（如 ±20ms 内不等直接丢帧/插帧）
//   6. 渲染层用 OpenGL ES / Direct3D 直接渲染 YUV，
//      避免 CPU 做 YUV→RGB 转换


