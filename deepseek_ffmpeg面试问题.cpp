// ----------------------------------------------------------------
// Q13: 音视频同步（A/V Sync）有哪些策略？FFmpeg 默认如何实现？
// ----------------------------------------------------------------
//
// 三种同步策略：
//
// | 策略           | 做法                                 | 优缺点                             |
// |----------------|--------------------------------------|------------------------------------|
// | 同步到音频     | 视频帧以音频时钟为基准显示/丢弃        | 最常用，音频连续播放，视频追赶       |
// | 同步到视频     | 音频以视频时钟为基准重采样             | 视频流畅，但音频可能有杂音          |
// | 同步到外部时钟 | 音视频都同步到系统时钟                 | 网络流场景常用                     |
//
// FFmpeg ffplay 默认策略：同步到音频。
//
//   // 核心同步逻辑简化版
//   double audio_clock = /* 当前音频播放到的 PTS 秒数 */;
//   double video_pts  = frame->pts * av_q2d(time_base);
//   double diff = video_pts - audio_clock; // 视频领先音频的秒数
//
//   if (diff > 0.01) {
//       // 视频太快，延迟显示（sleep 一段时间）
//       av_usleep(diff * 1000000);
//   } else if (diff < -0.01) {
//       // 视频太慢，丢帧追赶
//       av_frame_free(&frame); // 丢弃当前帧
//       continue;
//   }
//   // diff 在阈值内，正常渲染


// ----------------------------------------------------------------
// Q14: 直播场景中，如何保证不出现内存泄漏和帧堆积？
// ----------------------------------------------------------------
//
// 完善的音视频包队列设计要点：
//
//   class PacketQueue {
//       std::deque<AVPacket*> queue_;
//       std::mutex mtx_;
//       std::condition_variable cv_;
//       std::atomic<size_t> total_bytes_{0};
//       std::atomic<bool> abort_{false};
//
//       static constexpr size_t MAX_QUEUE_SIZE = 50;      // 最多缓存 50 帧
//       static constexpr size_t MAX_QUEUE_BYTES = 15 * 1024 * 1024; // 最多 15MB
//
//   public:
//       void push(AVPacket* pkt) {
//           std::unique_lock lock(mtx_);
//           // 流控：队列超过阈值则阻塞生产者（解码线程）
//           cv_.wait(lock, [this]{
//               return abort_ || (queue_.size() < MAX_QUEUE_SIZE
//                              && total_bytes_ < MAX_QUEUE_BYTES);
//           });
//           if (abort_) { av_packet_free(&pkt); return; }
//           total_bytes_ += pkt->size;
//           queue_.push_back(pkt);
//           cv_.notify_one();
//       }
//
//       void flush() {  // Seek 时清空旧数据
//           std::lock_guard lock(mtx_);
//           for (auto* pkt : queue_) av_packet_free(&pkt);
//           queue_.clear();
//           total_bytes_ = 0;
//           cv_.notify_all();
//       }
//
//       ~PacketQueue() {
//           abort_ = true;
//           cv_.notify_all();
//           flush();
//       }
//   };
//
// 关键防泄漏措施：
//   1. 流控（背压）：total_bytes_ 限制总内存，超出则阻塞生产者
//   2. abort 机制：析构时设置标志并唤醒所有等待线程
//   3. Seek flush：清除旧队列，防止播放跳跃后显示过期数据
//   4. RAII 包装：用智能指针/析构函数保证资源释放


