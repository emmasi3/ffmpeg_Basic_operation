//       packet_queue.push(pkt);
//       cv.notify_one();
//   }
//
//   // 消费者
//   AVPacket* consumer() {
//       std::unique_lock<std::mutex> lock(mtx);
//       cv.wait(lock, []{ return !packet_queue.empty(); });
//       AVPacket* pkt = packet_queue.front();
//       packet_queue.pop();
//       cv.notify_one();
